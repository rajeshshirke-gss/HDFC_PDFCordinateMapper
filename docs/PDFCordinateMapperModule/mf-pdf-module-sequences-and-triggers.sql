PROMPT Creating PDF module sequences when missing...

DECLARE
  PROCEDURE create_sequence_if_missing(
    p_sequence_name IN VARCHAR2,
    p_table_name    IN VARCHAR2,
    p_column_name   IN VARCHAR2
  ) IS
    v_count NUMBER;
    v_start_with NUMBER;
  BEGIN
    SELECT COUNT(*)
      INTO v_count
      FROM user_sequences
     WHERE sequence_name = UPPER(p_sequence_name);

    IF v_count = 0 THEN
      EXECUTE IMMEDIATE
        'SELECT NVL(MAX(' || p_column_name || '), 0) + 1 FROM ' || p_table_name
        INTO v_start_with;

      EXECUTE IMMEDIATE
        'CREATE SEQUENCE ' || p_sequence_name ||
        ' MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH ' ||
        GREATEST(v_start_with, 1) ||
        ' NOCACHE NOCYCLE';
    END IF;
  END;
BEGIN
  create_sequence_if_missing('MF_AMC_MASTER_SEQ', 'MF_AMC_MASTER', 'AUTOID');
  create_sequence_if_missing('MF_AMC_MASTER_APP_SEQ', 'MF_AMC_MASTER_APP', 'AUTOID');
  create_sequence_if_missing('MF_AMC_MASTER_LOG_SEQ', 'MF_AMC_MASTER_LOG', 'LOGID');

  create_sequence_if_missing('MF_TEMPLATE_MASTER_SEQ', 'MF_TEMPLATE_MASTER', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MASTER_APP_SEQ', 'MF_TEMPLATE_MASTER_APP', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MASTER_LOG_SEQ', 'MF_TEMPLATE_MASTER_LOG', 'LOGID');

  create_sequence_if_missing('MF_TEMPLATE_MAPPING_MAIN_SEQ', 'MF_TEMPLATE_MAPPING_MAIN', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MAPPING_MAIN_APP_SEQ', 'MF_TEMPLATE_MAPPING_MAIN_APP', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MAPPING_MAIN_LOG_SEQ', 'MF_TEMPLATE_MAPPING_MAIN_LOG', 'LOGID');

  create_sequence_if_missing('MF_TEMPLATE_MAPPING_FIELD_SEQ', 'MF_TEMPLATE_MAPPING_FIELD', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MAPPING_FIELD_APP_SEQ', 'MF_TEMPLATE_MAPPING_FIELD_APP', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MAPPING_FIELD_LOG_SEQ', 'MF_TEMPLATE_MAPPING_FIELD_LOG', 'LOGID');

  create_sequence_if_missing('MF_TEMPLATE_MAPPING_FIELD_CONFIG_SEQ', 'MF_TEMPLATE_MAPPING_FIELD_CONFIG', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MAPPING_FIELD_CONFIG_APP_SEQ', 'MF_TEMPLATE_MAPPING_FIELD_CONFIG_APP', 'AUTOID');
  create_sequence_if_missing('MF_TEMPLATE_MAPPING_FIELD_CONFIG_LOG_SEQ', 'MF_TEMPLATE_MAPPING_FIELD_CONFIG_LOG', 'LOGID');

  create_sequence_if_missing('MF_PDF_PROCESS_STATUS_MASTER_SEQ', 'MF_PDF_PROCESS_STATUS_MASTER', 'AUTOID');
  create_sequence_if_missing('MF_PDF_PROCESS_BATCH_SEQ', 'MF_PDF_PROCESS_BATCH', 'AUTOID');
  create_sequence_if_missing('MF_PDF_PROCESS_ROW_SEQ', 'MF_PDF_PROCESS_ROW', 'AUTOID');
  create_sequence_if_missing('MF_PDF_PROCESS_VALIDATION_ERROR_SEQ', 'MF_PDF_PROCESS_VALIDATION_ERROR', 'AUTOID');
  create_sequence_if_missing('MF_PDF_GENERATED_DOCUMENT_SEQ', 'MF_PDF_GENERATED_DOCUMENT', 'AUTOID');
  create_sequence_if_missing('MF_PDF_PROCESS_BATCH_LOG_SEQ', 'MF_PDF_PROCESS_BATCH_LOG', 'AUTOID');
