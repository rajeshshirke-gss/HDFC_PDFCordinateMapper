-- Purpose:
--   Generate AUTOID / LOGID values for MF_* tables.
--
-- Verified gap:
--   MF_* primary key columns are not identity columns and currently have no
--   MF_* sequences/triggers. Stored procedures should be able to insert rows
--   without manually calculating primary keys.
--
-- Style:
--   Matches existing Admin pattern:
--     USER_MASTER_APPROVAL_SEQ_TR
--     USER_MASTER_LOG_SEQ_TR
--     ROLE_MASTER_APPROVAL_SEQ_TR
